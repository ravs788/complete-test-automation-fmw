using System.Text;
using RabbitMQ.Client;
using RabbitMQ.Client.Events;

namespace Core.Messaging.RabbitMq;

/// <summary>
/// Listens to an exchange for the duration of a test: binds a server-named, exclusive, auto-delete queue, so the queue
/// disappears when the listener is disposed and nothing is left on the broker (R37). Start it before triggering the
/// behaviour under test, then wait with <see cref="WaitForAsync"/>.
/// </summary>
public sealed class RabbitMqListener : IAsyncDisposable
{
    private readonly IConnection _connection;
    private readonly IChannel _channel;

    private RabbitMqListener(IConnection connection, IChannel channel, string queue)
    {
        _connection = connection;
        _channel = channel;
        Queue = queue;
    }

    /// <summary>The temporary queue's name (generated by the broker).</summary>
    public string Queue { get; }

    public MessageCollector<ReceivedMessage> Messages { get; } = new();

    /// <param name="uri">Broker URI, e.g. <c>amqp://user:pass@host:5672/vhost</c> (keep the password as a secret:// setting).</param>
    /// <param name="exchange">Exchange to listen to (must exist).</param>
    /// <param name="routingKey">Binding key; <c>#</c> receives everything from a topic exchange.</param>
    /// <param name="cancellationToken"></param>
    public static async Task<RabbitMqListener> StartAsync(string uri, string exchange, string routingKey = "#",
        CancellationToken cancellationToken = default)
    {
        var connection = await new ConnectionFactory { Uri = new Uri(uri) }.CreateConnectionAsync(cancellationToken);
        var channel = await connection.CreateChannelAsync(cancellationToken: cancellationToken);
        var queue = (await channel.QueueDeclareAsync("", durable: false, exclusive: true, autoDelete: true,
            cancellationToken: cancellationToken)).QueueName;
        await channel.QueueBindAsync(queue, exchange, routingKey, cancellationToken: cancellationToken);

        var listener = new RabbitMqListener(connection, channel, queue);
        var consumer = new AsyncEventingBasicConsumer(channel);
        consumer.ReceivedAsync += (_, delivery) =>
        {
            listener.Messages.Add(new ReceivedMessage
            {
                Source = $"{delivery.Exchange}/{delivery.RoutingKey}",
                Key = delivery.RoutingKey,
                Body = Encoding.UTF8.GetString(delivery.Body.Span),
                Headers = delivery.BasicProperties.Headers?.ToDictionary(
                    h => h.Key, h => h.Value is byte[] bytes ? Encoding.UTF8.GetString(bytes) : h.Value?.ToString() ?? "")
                          ?? new Dictionary<string, string>()
            });
            return Task.CompletedTask;
        };
        await channel.BasicConsumeAsync(queue, autoAck: true, consumer, cancellationToken);
        return listener;
    }

    public Task<ReceivedMessage> WaitForAsync(Func<ReceivedMessage, bool> match, TimeSpan timeout, string description = "a matching message") =>
        Messages.WaitForAsync(match, timeout, description);

    public async ValueTask DisposeAsync()
    {
        await _channel.CloseAsync();
        await _connection.CloseAsync();
        _channel.Dispose();
        _connection.Dispose();
    }
}
